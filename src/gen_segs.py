_cur = None

def BLOCK(key):
    """开一个新的分镜块，后续 A() 的句子都挂在这个场景上。"""
    global _cur
    BLOCKS.append({"key": key, "r0": len(S), "r1": len(S) - 1})
    _cur = BLOCKS[-1]

def A(text, cap="", hold=0.42):
    S.append({"text": text, "cap": cap, "hold": hold})
    _cur["r1"] = len(S) - 1

